// Lower case, without accents, and with every run of punctuation or spaces
// turned into one space.
const key = (name: string) =>
  name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

const arabicByKey = new Map(arabic.flatMap(([ar, ...names]) => names.map((name) => [key(name), ar] as const)));

// The team's name for the page's language.
export function teamName(team: Team, locale: Locale): string {
  if (locale === "ar") return arabicByKey.get(key(team.name)) ?? team.name;
  return team.name;
}
